"""Build the generated lookup files the map page reads:

  js/directory-assets.js    asset names -> files the cards show: web copies in assets/media
                            (from scripts/optimize-media.py) for dataset codes (e.g. "23-sl"),
                            plus website screenshots ("23-web") in assets/websites.
                            DIRECTORY_ASSETS_FULL maps the same codes to the full-resolution
                            originals in ASSET/DesignDirectory (opened by the zoom viewer).
  js/directory-services.js  services_all codes (e.g. "17") -> labels from DATASET/AllServices_Code.csv
  js/directory-data.js      the agency dataset, so the list shows before the map has loaded

Run after adding or renaming photos, or editing the services list:
  python3 scripts/build-directory-data.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORIGINALS = ROOT / "ASSET" / "DesignDirectory"
WEB_COPIES = ROOT / "assets" / "media"
WEBSITES = ROOT / "assets" / "websites"
AGENCY_CSV = ROOT / "DATASET" / "01_DD_Data_Agency_NORMALIZED.csv"
NUMERIC_FIELDS = {"place_id", "est", "staff_count"}
SERVICES_CSV = ROOT / "DATASET" / "AllServices_Code.csv"
# When one name has several files, prefer the first extension in this list.
PREFERENCE = [".webp", ".jpg", ".jpeg", ".png", ".avif", ".gif", ".mp4"]


def write_js(path, global_name, data, source):
    path.write_text(
        f"// Generated by scripts/build-directory-data.py from {source} — do not edit by hand.\n"
        f"window.{global_name} = {json.dumps(data, indent=2, ensure_ascii=False)};\n"
    )
    print(f"{len(data)} entries -> {path.relative_to(ROOT)}")


def index_dir(folder):
    index = {}
    if not folder.exists():
        return index
    for f in sorted(folder.iterdir()):
        if f.suffix.lower() not in PREFERENCE:
            continue
        current = index.get(f.stem)
        if current is None or PREFERENCE.index(f.suffix.lower()) < PREFERENCE.index(Path(current).suffix.lower()):
            index[f.stem] = f.relative_to(ROOT).as_posix()
    return index


def build_assets():
    originals = index_dir(ORIGINALS)
    shown = {**originals, **index_dir(WEB_COPIES), **index_dir(WEBSITES)}  # web copy wins when present
    path = ROOT / "js" / "directory-assets.js"
    path.write_text(
        "// Generated by scripts/build-directory-data.py — do not edit by hand.\n"
        f"window.DIRECTORY_ASSETS = {json.dumps(dict(sorted(shown.items())), indent=2)};\n"
        f"window.DIRECTORY_ASSETS_FULL = {json.dumps(dict(sorted(originals.items())), indent=2)};\n"
    )
    print(f"{len(shown)} shown / {len(originals)} originals -> {path.relative_to(ROOT)}")


def build_agency_data():
    with AGENCY_CSV.open(encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f, delimiter=";"))
    data = []
    for row in rows:
        entry = {}
        for key, value in row.items():
            value = (value or "").strip()
            if key in NUMERIC_FIELDS and value.isdigit():
                entry[key] = int(value)
            elif key in ("latitude", "longitude"):
                entry[key] = float(value)
            else:
                entry[key] = value
        data.append(entry)
    path = ROOT / "js" / "directory-data.js"
    path.write_text(  # compact: this one ships on every page load
        f"// Generated by scripts/build-directory-data.py from {AGENCY_CSV.relative_to(ROOT).as_posix()} — do not edit by hand.\n"
        f"window.DIRECTORY_DATA = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n"
    )
    print(f"{len(data)} agencies -> {path.relative_to(ROOT)}")


def build_services():
    with SERVICES_CSV.open(encoding="utf-8-sig", newline="") as f:
        services = {row["code"].strip(): row["label"].strip() for row in csv.DictReader(f) if row["code"].strip()}
    write_js(ROOT / "js" / "directory-services.js", "DIRECTORY_SERVICES", services, "DATASET/AllServices_Code.csv")


if __name__ == "__main__":
    build_assets()
    build_services()
    build_agency_data()
